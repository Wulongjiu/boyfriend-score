/** 按总分匹配档位 */
export function getLevel(score: number): Level {
  const level = LEVELS.find((l) => score >= l.min && score <= l.max);
  // 兜底：理论上 0–100 一定命中，防御性返回最低档
  return level ?? LEVELS[LEVELS.length - 1];
}
